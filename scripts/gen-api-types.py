#!/usr/bin/env python3
"""Generate frontend/src/lib/api.generated.ts from the API's OpenAPI schema. No downloads.

Usage: python3 scripts/gen-api-types.py [URL_OR_FILE]   (default http://localhost:8000/openapi.json)

Field rules: a field is required if the schema lists it as required. On response models (names not
ending in "Request") a field with a non-null default is also required, because the server always
sends it (a default_factory field has no "default" key and counts too); fields whose default is
null stay optional and nullable. Request-model fields with
defaults stay optional, so callers can leave them out.
"""
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "lib" / "api.generated.ts"
SKIP = {"HTTPValidationError", "ValidationError"}


def load(src: str) -> dict:
    if src.startswith("http"):
        with urllib.request.urlopen(src, timeout=15) as r:
            return json.load(r)
    return json.loads(Path(src).read_text())


def ts(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in s:
        parts = []
        for p in s["anyOf"]:
            t = ts(p)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    t = s.get("type")
    if t == "null":
        return "null"
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "array":
        inner = ts(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        key = "string"
        if "propertyNames" in s and "enum" in s["propertyNames"]:
            key = " | ".join(json.dumps(v) for v in s["propertyNames"]["enum"])
            val = ts(ap) if isinstance(ap, dict) else "unknown"
            return f"Partial<Record<{key}, {val}>>"
        if isinstance(ap, dict) and ap:
            return f"Record<{key}, {ts(ap)}>"
        return "Record<string, any>"
    return "unknown"


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000/openapi.json"
    spec = load(src)
    schemas = spec["components"]["schemas"]
    lines = [
        "// Generated by scripts/gen-api-types.py from /api/openapi.json. Do not edit by hand;",
        "// change contracts/api_models.py, then rerun the script.",
        "/* eslint-disable @typescript-eslint/no-explicit-any */",
        f"// API: {spec.get('info', {}).get('title', '')} {spec.get('info', {}).get('version', '')}",
        "",
    ]
    for name in sorted(schemas):
        if name in SKIP:
            continue
        s = schemas[name]
        is_request = name.endswith("Request")
        req = set(s.get("required", []))
        lines.append(f"export interface {name} {{")
        for field, fs in s.get("properties", {}).items():
            # A response field without a "default" key uses default_factory: always sent.
            required = field in req or (not is_request and fs.get("default", ...) is not None)
            desc = fs.get("description")
            if desc:
                lines.append(f"  /** {desc} */")
            lines.append(f"  {field}{'' if required else '?'}: {ts(fs)};")
        lines.append("}")
        lines.append("")
    paths = []
    for path, ops in spec.get("paths", {}).items():
        for method in ops:
            paths.append(f"  | \"{method.upper()} {path}\"")
    lines.append("/** Every operation the API serves (paths are relative to /api). */")
    lines.append("export type ApiOperation =")
    lines.extend(paths or ['  never'])
    lines[-1] += ";"
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(schemas) - len(SKIP & set(schemas))} types, {len(paths)} operations")


if __name__ == "__main__":
    main()
